/// In-flight request bookkeeping: logged when the response is ready, or as 499 (like
/// nginx's "client closed request") if the client gave up and the request was dropped.
struct LogGuard {
    state: Arc<AppState>,
    method: String,
    path: String,
    path_and_query: String,
    start: Instant,
    fault: FaultSlot,
    done: bool,
}

impl LogGuard {
    fn finish(&mut self, status: u16) {
        self.done = true;
        let ms = self.start.elapsed().as_millis() as u64;
        let fault = self.fault.lock().unwrap_or_else(|e| e.into_inner()).clone();
        let (method, path) = (&self.method, &self.path);
        match &fault {
            Some(f) => tracing::info!("{method} {path} -> {status} ({ms} ms) [fault: {f}]"),
            None => tracing::info!("{method} {path} -> {status} ({ms} ms)"),
        }
        if !path.starts_with("/_admin/") {
            self.state.log_request(RequestRecord {
                method: self.method.clone(),
                path: self.path_and_query.clone(),
                status,
                ms,
                fault,
            });
        }
    }
}

impl Drop for LogGuard {
    fn drop(&mut self) {
        if !self.done {
            self.finish(499);
        }
    }
}

/// Where `inject_faults` records the applied fault for the logger.
type FaultSlot = Arc<Mutex<Option<String>>>;

async fn log_requests(
    State(state): State<Arc<AppState>>,
    mut req: Request,
    next: Next,
) -> Response {
    let path = req.uri().path().to_owned();
    let slot: FaultSlot = Arc::default();
    req.extensions_mut().insert(Arc::clone(&slot));
    let mut guard = LogGuard {
        state,
        method: req.method().to_string(),
        path_and_query: req
            .uri()
            .path_and_query()
            .map_or_else(|| path.clone(), |p| p.as_str().to_owned()),
        path,
        start: Instant::now(),
        fault: slot,
        done: false,
    };
    let resp = next.run(req).await;
    guard.finish(resp.status().as_u16());
    resp
}

/// Applies the `X-Fake-Fault` header, else the matching fault rules.
async fn inject_faults(State(state): State<Arc<AppState>>, req: Request, next: Next) -> Response {
    let header_faults = req
        .headers()
        .get(FAULT_HEADER)
        .and_then(|v| v.to_str().ok())
        .map(parse_fault_header);
    let (delay, answer, source) = match header_faults {
        Some(kinds) => {
            let mut delay = 0;
            let mut answer = None;
            for k in kinds {
                match k {
                    FaultKind::Latency { ms } => delay += ms,
                    other if answer.is_none() => answer = Some(other),
                    _ => {}
                }
            }
            (delay, answer, "header")
        }
        None => {
            let (delay, answer) = state.take_faults(req.method().as_str(), req.uri().path());
            (delay, answer, "rule")
        }
    };
    let mut labels = Vec::new();
    if delay > 0 {
        labels.push(format!("latency {delay}ms"));
    }
    if let Some(kind) = &answer {
        labels.push(match kind {
            FaultKind::Status { status } => format!("status {status}"),
            FaultKind::RateLimit { retry_after } => format!("rate_limit {retry_after}s"),
            _ => format!("{kind:?}"),
        });
    }
    if !labels.is_empty()
        && let Some(slot) = req.extensions().get::<FaultSlot>()
    {
        *slot.lock().unwrap_or_else(|e| e.into_inner()) =
            Some(format!("{} ({source})", labels.join(" + ")));
    }
    if delay > 0 {
        tokio::time::sleep(Duration::from_millis(delay)).await;
    }
    match &answer {
        Some(kind) => fault_response(kind),
        None => next.run(req).await,
    }
}

fn fault_response(kind: &FaultKind) -> Response {
    let rate_limited = |retry_after: u64| {
        (
            StatusCode::TOO_MANY_REQUESTS,
            [
                (header::RETRY_AFTER, retry_after.to_string()),
                (
                    header::HeaderName::from_static("x-ratelimit-remaining"),
                    "0".to_owned(),
                ),
            ],
            Json(json!({ "error": "Too Many Attempts." })),
        )
            .into_response()
    };
    match *kind {
        FaultKind::Status { status: 401 } => invalid_token(),
        FaultKind::Status { status: 429 } => rate_limited(1),
        FaultKind::RateLimit { retry_after } => rate_limited(retry_after),
        FaultKind::Status { status } => {
            let code = StatusCode::from_u16(status).unwrap_or(StatusCode::INTERNAL_SERVER_ERROR);
            let reason = code.canonical_reason().unwrap_or("Injected fault");
            (code, Json(json!({ "error": reason }))).into_response()
        }
        // Not answers (handled before / at rule creation).
        FaultKind::Latency { .. } | FaultKind::ExpireTokens => {
            StatusCode::INTERNAL_SERVER_ERROR.into_response()
        }
    }
}

