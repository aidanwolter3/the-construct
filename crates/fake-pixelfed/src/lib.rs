/// Numeric ids sort numerically (snowflakes), anything else after them as text.
fn id_order(a: &str, b: &str) -> std::cmp::Ordering {
    match (a.parse::<u128>(), b.parse::<u128>()) {
        (Ok(x), Ok(y)) => x.cmp(&y),
        (Ok(_), Err(_)) => std::cmp::Ordering::Less,
        (Err(_), Ok(_)) => std::cmp::Ordering::Greater,
        (Err(_), Err(_)) => a.cmp(b),
    }
}

impl Inner {
    /// Direct replies to `id`, oldest first.
    fn reply_ids(&self, id: &str) -> Vec<String> {
        let mut ids: Vec<String> = self
            .statuses
            .iter()
            .filter(|(_, s)| s["in_reply_to_id"].as_str() == Some(id))
            .map(|(k, _)| k.clone())
            .collect();
        ids.sort_by(|a, b| id_order(a, b));
        ids
    }

    /// The parent chain of `id`, root first (Mastodon `ancestors`).
    fn ancestors(&self, id: &str) -> Vec<String> {
        let mut chain = Vec::new();
        let mut cur = id;
        while let Some(parent) = self
            .statuses
            .get(cur)
            .and_then(|s| s["in_reply_to_id"].as_str())
        {
            if !self.statuses.contains_key(parent) || chain.iter().any(|c| c == parent) {
                break;
            }
            chain.push(parent.to_owned());
            cur = parent;
        }
        chain.reverse();
        chain
    }

    /// Pixelfed's `context`: the direct parent only, and the direct replies only (oldest
    /// first, at most [`CONTEXT_REPLY_LIMIT`]), and none at all while `replies_count` is 0.
    fn pixelfed_context(&self, id: &str) -> (Vec<String>, Vec<String>) {
        let Some(status) = self.statuses.get(id) else {
            return (Vec::new(), Vec::new());
        };
        let parent = status["in_reply_to_id"]
            .as_str()
            .filter(|p| self.statuses.contains_key(*p))
            .map(str::to_owned);
        let mut replies = Vec::new();
        if status["replies_count"].as_i64().unwrap_or(0) > 0 {
            replies = self.reply_ids(id);
            replies.truncate(CONTEXT_REPLY_LIMIT);
        }
        (parent.into_iter().collect(), replies)
    }

    /// Every reply below `id`, depth first, siblings oldest first (Mastodon `descendants`).
    fn descendants(&self, id: &str) -> Vec<String> {
        let mut children: HashMap<&str, Vec<&str>> = HashMap::new();
        for (k, s) in &self.statuses {
            if let Some(parent) = s["in_reply_to_id"].as_str() {
                children.entry(parent).or_default().push(k);
            }
        }
        for list in children.values_mut() {
            list.sort_by(|a, b| id_order(a, b));
        }
        let mut out = Vec::new();
        let mut stack: Vec<&str> = children
            .get(id)
            .into_iter()
            .flatten()
            .rev()
            .copied()
            .collect();
        while let Some(next) = stack.pop() {
            if next == id || out.iter().any(|o| o == next) {
                continue;
            }
            out.push(next.to_owned());
            stack.extend(children.get(next).into_iter().flatten().rev().copied());
        }
        out
    }

    /// The status JSON with its current state, with the reblogged status nested.
    fn render(&self, id: &str) -> Option<Value> {
        let mut status = self.statuses.get(id)?.clone();
        if let Some(inner) = self.reblog_of.get(id) {
            status["reblog"] = self.render(inner).unwrap_or(Value::Null);
        }
        Some(status)
    }

    /// Mastodon semantics: acting on a reblog acts on the reblogged status.
    fn target_id(&self, id: &str) -> Option<String> {
        let target = self.reblog_of.get(id).map_or(id, String::as_str);
        self.statuses
            .contains_key(target)
            .then(|| target.to_owned())
    }
}

