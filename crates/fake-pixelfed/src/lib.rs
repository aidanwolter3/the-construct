// ---------- fault injection ----------

/// What a [`FaultRule`] does to a matching request.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum FaultKind {
    /// Answer with this status instead of handling the request. 401 looks like an expired
    /// token (`{"error":"The access token is invalid"}` + `WWW-Authenticate`), 429 carries
    /// `Retry-After: 1`, anything else `{"error":"<reason>"}`.
    Status { status: u16 },
    /// 429 `{"error":"Too Many Attempts."}` with `Retry-After: <retry_after>` (seconds).
    RateLimit {
        #[serde(default = "one")]
        retry_after: u64,
    },
    /// Delay the request by `ms`, then handle it normally.
    Latency { ms: u64 },
    /// Not a stored rule: every access token stops working when the rule is added (refresh
    /// tokens stay valid), as with [`AppState::expire_access_tokens`].
    ExpireTokens,
}

fn one() -> u64 {
    1
}

/// A fault applied to requests whose path starts with `path_prefix` (all non-admin paths
/// when absent) and, if set, whose method is `method`, for the next `times` matches
/// (forever when absent).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct FaultRule {
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub path_prefix: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub method: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub times: Option<u32>,
    #[serde(flatten)]
    pub kind: FaultKind,
}

impl FaultRule {
    pub fn new(kind: FaultKind) -> Self {
        Self {
            path_prefix: None,
            method: None,
            times: None,
            kind,
        }
    }
    /// Answer `status` (see [`FaultKind::Status`]).
    pub fn status(status: u16) -> Self {
        Self::new(FaultKind::Status { status })
    }
    pub fn rate_limit(retry_after: u64) -> Self {
        Self::new(FaultKind::RateLimit { retry_after })
    }
    pub fn latency(ms: u64) -> Self {
        Self::new(FaultKind::Latency { ms })
    }
    pub fn expire_tokens() -> Self {
        Self::new(FaultKind::ExpireTokens)
    }
    pub fn path(mut self, prefix: &str) -> Self {
        self.path_prefix = Some(prefix.to_owned());
        self
    }
    pub fn method(mut self, method: &str) -> Self {
        self.method = Some(method.to_ascii_uppercase());
        self
    }
    pub fn times(mut self, n: u32) -> Self {
        self.times = Some(n);
        self
    }

    fn matches(&self, method: &str, path: &str) -> bool {
        self.path_prefix
            .as_deref()
            .is_none_or(|p| path.starts_with(p))
            && self
                .method
                .as_deref()
                .is_none_or(|m| m.eq_ignore_ascii_case(method))
    }
}

/// Parses an `X-Fake-Fault` value: comma-separated `401`, `429`, any other status code, or
/// `latency=<ms>` (e.g. `latency=1500,503`). Unknown parts are ignored.
pub fn parse_fault_header(value: &str) -> Vec<FaultKind> {
    value
        .split(',')
        .filter_map(|part| {
            let part = part.trim();
            if let Some(ms) = part.strip_prefix("latency=") {
                return ms.trim().parse().ok().map(|ms| FaultKind::Latency { ms });
            }
            match part.parse::<u16>() {
                Ok(status) if (100..=599).contains(&status) => Some(FaultKind::Status { status }),
                _ => None,
            }
        })
        .collect()
}

/// One entry of the request log (`GET /_admin/state`, [`AppState::requests`]).
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct RequestRecord {
    pub method: String,
    /// Path and query.
    pub path: String,
    /// 499: the client closed the connection before the answer (e.g. its timeout).
    pub status: u16,
    pub ms: u64,
    /// The injected fault, e.g. `status 503 (rule)` or `latency 1500ms (header)`.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub fault: Option<String>,
}

