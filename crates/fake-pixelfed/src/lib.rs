/// `GET /api/v1/statuses/:id/context`: the thread around a status. Like Pixelfed, only one
/// level each way (the parent; the direct replies), so a client must ask again for the
/// replies to a reply; Mastodon's whole thread with [`AppState::with_mastodon_threads`]. On
/// a reblog, the reblogged status's thread.
async fn status_context(
    State(state): State<Arc<AppState>>,
    headers: HeaderMap,
    UrlPath((id, action)): UrlPath<(String, String)>,
) -> Response {
    if action != "context" {
        return not_found();
    }
    if let Err(r) = require_token(&state, &headers) {
        return r;
    }
    let inner = state.lock();
    let Some(target) = inner.target_id(&id) else {
        return not_found();
    };
    let (ancestors, descendants) = if state.mastodon_threads {
        (inner.ancestors(&target), inner.descendants(&target))
    } else {
        inner.pixelfed_context(&target)
    };
    let render =
        |ids: Vec<String>| -> Vec<Value> { ids.iter().filter_map(|id| inner.render(id)).collect() };
    Json(json!({
        "ancestors": render(ancestors),
        "descendants": render(descendants),
    }))
    .into_response()
}

/// `POST /api/v1/statuses`: comments only (`in_reply_to_id` required; Pixelfed wants media
/// for a new post, which the fake does not take). Form or JSON body; honours
/// `Idempotency-Key`.
async fn create_status(
    State(state): State<Arc<AppState>>,
    headers: HeaderMap,
    body: Bytes,
) -> Response {
    if let Err(r) = require_token(&state, &headers) {
        return r;
    }
    let params = match parse_params(&headers, &body) {
        Ok(p) => p,
        Err(r) => return r,
    };
    let idempotency_key = headers
        .get("idempotency-key")
        .and_then(|v| v.to_str().ok())
        .map(str::trim)
        .filter(|k| !k.is_empty())
        .map(str::to_owned);
    let text = params.get("status").map_or("", |s| s.trim());
    let reply_to = param(&params, "in_reply_to_id");
    let visibility = match param(&params, "visibility") {
        "" => "public",
        v @ ("public" | "unlisted" | "private" | "direct") => v,
        _ => return unprocessable("Validation failed: Visibility is invalid"),
    };
    let spoiler_text = param(&params, "spoiler_text");
    let sensitive = matches!(param(&params, "sensitive"), "true" | "1") || !spoiler_text.is_empty();

    let mut inner = state.lock();
    if let Some(key) = &idempotency_key
        && let Some((_, id)) = inner.idempotency.iter().find(|(k, _)| k == key)
        && let Some(existing) = inner.render(id)
    {
        tracing::info!(status_id = %id, key, "idempotent replay of a created status");
        return Json(existing).into_response();
    }
    if reply_to.is_empty() {
        return unprocessable(
            "Validation failed: in_reply_to_id is required (the fake only creates comments)",
        );
    }
    if text.is_empty() {
        return unprocessable("Validation failed: Text can't be blank");
    }
    if text.chars().count() > MAX_STATUS_CHARS {
        return unprocessable(&format!(
            "Validation failed: Text is too long (maximum is {MAX_STATUS_CHARS} characters)"
        ));
    }
    let Some(parent_id) = inner.target_id(reply_to) else {
        tracing::info!(in_reply_to_id = %reply_to, "comment on an unknown status");
        return not_found();
    };
    let id = inner.next_status_id.to_string();
    inner.next_status_id += 1;
    let now = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map_or(0, |d| d.as_secs());
    let parent = &inner.statuses[&parent_id];
    let mut status = comment_status(
        &state.public_url,
        &id,
        &state.self_account,
        parent,
        text,
        &status_time(now),
    );
    status["visibility"] = json!(visibility);
    status["spoiler_text"] = json!(spoiler_text);
    status["sensitive"] = json!(sensitive);
    let parent = inner
        .statuses
        .get_mut(&parent_id)
        .expect("target_id checked");
    parent["replies_count"] = json!(parent["replies_count"].as_i64().unwrap_or(0) + 1);
    inner.statuses.insert(id.clone(), status);
    inner.created.push(id.clone());
    if let Some(key) = idempotency_key {
        if inner.idempotency.len() == IDEMPOTENCY_CAP {
            inner.idempotency.pop_front();
        }
        inner.idempotency.push_back((key, id.clone()));
    }
    tracing::info!(status_id = %id, in_reply_to_id = %parent_id, "comment created");
    Json(inner.render(&id)).into_response()
}

/// `DELETE /api/v1/statuses/:id`: only the signed-in account's own statuses. Returns the
/// deleted status with its source `text` (Mastodon's delete-and-redraft shape).
async fn delete_status(
    State(state): State<Arc<AppState>>,
    headers: HeaderMap,
    UrlPath(id): UrlPath<String>,
) -> Response {
    if let Err(r) = require_token(&state, &headers) {
        return r;
    }
    let mut inner = state.lock();
    let Some(status) = inner.render(&id) else {
        return not_found();
    };
    if status["account"]["id"] != state.self_account["id"] {
        return (
            StatusCode::FORBIDDEN,
            Json(json!({ "error": "This action is not allowed" })),
        )
            .into_response();
    }
    inner.statuses.remove(&id);
    inner.timeline.retain(|t| *t != id);
    inner.reblog_of.remove(&id);
    if let Some(parent_id) = status["in_reply_to_id"].as_str()
        && let Some(parent) = inner.statuses.get_mut(parent_id)
    {
        parent["replies_count"] = json!((parent["replies_count"].as_i64().unwrap_or(0) - 1).max(0));
    }
    tracing::info!(status_id = %id, "status deleted");
    let mut deleted = status;
    deleted["text"] = deleted["content_text"].clone();
    Json(deleted).into_response()
}

async fn media(State(state): State<Arc<AppState>>, UrlPath(path): UrlPath<String>) -> Response {
    let rel = Path::new(&path);
    if path.contains('\\') || !rel.components().all(|c| matches!(c, Component::Normal(_))) {
        return StatusCode::NOT_FOUND.into_response();
    }
    let bytes = match &state.media_dir {
        Some(dir) => match tokio::fs::read(dir.join(rel)).await {
            Ok(b) => Body::from(b),
            Err(_) => return StatusCode::NOT_FOUND.into_response(),
        },
        None => match embedded(&format!("media/{path}")) {
            Some(b) => Body::from(b),
            None => return StatusCode::NOT_FOUND.into_response(),
        },
    };
    let content_type = match rel
        .extension()
        .and_then(|e| e.to_str())
        .map(str::to_ascii_lowercase)
        .as_deref()
    {
        Some("png") => "image/png",
        Some("jpg" | "jpeg") => "image/jpeg",
        Some("gif") => "image/gif",
        Some("webp") => "image/webp",
        _ => "application/octet-stream",
    };
    (
        [
            (header::CONTENT_TYPE, content_type),
            (header::CACHE_CONTROL, "public, max-age=3600"),
        ],
        bytes,
    )
        .into_response()
}

