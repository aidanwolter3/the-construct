//! A fake Pixelfed (Mastodon-compatible) upstream for local development and tests.
//!
//! Serves the fixtures in `fixtures/pixelfed/` with in-memory state: OAuth app registration, an
//! authorization-code + PKCE (S256) flow, refresh_token and client_credentials grants, bearer-token checks, the home timeline,
//! favourite/bookmark toggles, comments (reply threads from `comments.json`: read a thread with
//! `GET /api/v1/statuses/:id/context`, add one with `POST /api/v1/statuses` + `in_reply_to_id`,
//! delete your own) and static media under `/storage/...`. Every `{{BASE}}` in the fixture
//! JSON is replaced by the configured public URL when the fixtures are loaded.
//!
//! The fixtures are also embedded into the binary at compile time (`build.rs`), so a single
//! executable runs anywhere; an empty [`Config::fixtures_dir`] selects them.
//!
//! Test controls (docs/DECISIONS.md D16), available both in-process ([`AppState::reset`],
//! [`AppState::add_faults`], [`AppState::report`], ...) and over HTTP under `/_admin` (when
//! [`AppState::with_admin`] is on): reset to the fixture state, a state report with a request log,
//! and fault injection (status codes, an expired-token 401, 429 with `Retry-After`, latency) by
//! rule or by a per-request `X-Fake-Fault` header.

